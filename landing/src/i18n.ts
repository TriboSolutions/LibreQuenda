// Every text on the landing, per language. Galician is the default and lives at /;
// the others at /es/, /ca/, /en/ and /pt/.

export const LANGS = ["gl", "es", "ca", "en", "pt"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "gl";

export const LANG_NAMES: Record<Lang, string> = {
  gl: "Galego",
  es: "Español",
  ca: "Català",
  en: "English",
  pt: "Português",
};

/** The path of a page in a language: "/" + "instalar" -> "/es/instalar" */
export function href(lang: Lang, path = "/"): string {
  const p = path.startsWith("/") ? path : `/${path}`;
  return lang === DEFAULT_LANG ? p : `/${lang}${p === "/" ? "/" : p}`;
}

/** The same page in another language */
export function swapLang(pathname: string, to: Lang): string {
  const rest = pathname.replace(/^\/(es|ca|en|pt)(?=\/|$)/, "") || "/";
  return href(to, rest);
}

